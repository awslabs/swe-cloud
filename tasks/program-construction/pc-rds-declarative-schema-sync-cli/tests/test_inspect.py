"""Inspecting live databases: HCL structure, SQL and JSON formats, filters and round trips."""

from library_state import LIBRARY_CATALOG, LIBRARY_ORDER, LIBRARY_PLAN
from schema_sync import (
    EMPTY_DATABASE,
    assert_catalog,
    assert_hcl,
    assert_plan,
    assert_synced,
    expected,
    json_document,
    ok,
)

PUBLIC_SCHEMA = ['CREATE SCHEMA IF NOT EXISTS "public"', """COMMENT ON SCHEMA "public" IS 'standard public schema'"""]


def apply(ctx, state):
    target, dev = ctx.database(), ctx.database()
    ctx.fixture(state)
    ok(ctx.run("schema", "apply", "-u", ctx.url(target), "--to", f"file://{state}", "--dev-url", ctx.url(dev),
               "--auto-approve"))
    return target, dev


def test_inspect_hcl_of_an_applied_state(ctx):
    target, _ = apply(ctx, "library.hcl")
    assert_hcl(ok(ctx.run("schema", "inspect", "-u", ctx.url(target))), expected("library.inspect.hcl"))
    assert_hcl(ok(ctx.run("schema", "inspect", "-u", ctx.url(target, "public"))), expected("library.inspect.hcl"))


def test_inspect_empty_database(ctx):
    db = ctx.database()
    assert_hcl(ok(ctx.run("schema", "inspect", "-u", ctx.url(db))),
               'schema "public" {\n  comment = "standard public schema"\n}\n')
    assert_plan(ok(ctx.run("schema", "inspect", "-u", ctx.url(db), "--format", "{{ sql . }}")), PUBLIC_SCHEMA, [(0, 1)])


def test_inspect_sql_format(ctx):
    target, _ = apply(ctx, "library.hcl")
    out = ok(ctx.run("schema", "inspect", "-u", ctx.url(target), "--format", "{{ sql . }}"))
    order = [(0, 1), (0, 2), (0, 3), (0, 4)] + [(a + 2, b + 2) for a, b in LIBRARY_ORDER]
    assert_plan(out, PUBLIC_SCHEMA + LIBRARY_PLAN, order)
    assert not any(line.startswith("  ") for line in out.splitlines())
    # An indent argument prints the same statements with table bodies on indented lines.
    indented = ok(ctx.run("schema", "inspect", "-u", ctx.url(target), "--format", '{{ sql . "  " }}'))
    assert_plan(indented, PUBLIC_SCHEMA + LIBRARY_PLAN, order)
    assert '  "id" bigserial NOT NULL,' in indented.splitlines()


def test_inspected_state_round_trips_to_a_new_database(ctx):
    source, _ = apply(ctx, "library.hcl")
    copy, dev = ctx.database(), ctx.database()
    ctx.write("copy.hcl", ok(ctx.run("schema", "inspect", "-u", ctx.url(source))))
    out = ok(ctx.run("schema", "apply", "-u", ctx.url(copy), "--to", "file://copy.hcl", "--dev-url", ctx.url(dev),
                     "--auto-approve"))
    assert_plan(out, LIBRARY_PLAN, LIBRARY_ORDER)
    assert_catalog(ctx, copy, LIBRARY_CATALOG)
    assert_synced(ok(ctx.run("schema", "diff", "--from", ctx.url(source), "--to", ctx.url(copy))))


PETS_SQL = """
CREATE TYPE color AS ENUM ('red', 'green');
CREATE TABLE owners (id serial PRIMARY KEY, name varchar NOT NULL);
CREATE TABLE pets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id int REFERENCES owners (id) ON DELETE CASCADE,
  born timestamp(3), weight numeric, fur color DEFAULT 'red', nick text DEFAULT 'rex', flags boolean[],
  ok boolean DEFAULT false,
  CONSTRAINT pets_nick_born UNIQUE (nick, born), CONSTRAINT weight_pos CHECK (weight > 0));
CREATE INDEX pets_lower_nick ON pets (lower(nick)) WHERE ok;
COMMENT ON TABLE pets IS 'animals';
COMMENT ON COLUMN pets.nick IS 'short name';
"""

PETS_STATEMENTS = PUBLIC_SCHEMA + [
    """CREATE TYPE "public"."color" AS ENUM ('red', 'green')""",
    """CREATE TABLE "public"."owners" ("id" serial NOT NULL, "name" character varying NOT NULL, PRIMARY KEY ("id"))""",
    """CREATE TABLE "public"."pets" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "owner_id" integer NULL,
      "born" timestamp(3) NULL, "weight" numeric NULL, "fur" "public"."color" NULL DEFAULT 'red',
      "nick" text NULL DEFAULT 'rex', "flags" boolean[] NULL, "ok" boolean NULL DEFAULT false, PRIMARY KEY ("id"),
      CONSTRAINT "pets_nick_born" UNIQUE ("nick", "born"), CONSTRAINT "pets_owner_id_fkey" FOREIGN KEY ("owner_id")
      REFERENCES "public"."owners" ("id") ON UPDATE NO ACTION ON DELETE CASCADE,
      CONSTRAINT "weight_pos" CHECK (weight > (0)::numeric))""",
    """CREATE INDEX "pets_lower_nick" ON "public"."pets" ((lower(nick))) WHERE ok""",
    """COMMENT ON TABLE "public"."pets" IS 'animals'""",
    """COMMENT ON COLUMN "public"."pets"."nick" IS 'short name'""",
]


def test_inspect_objects_created_outside_the_program(ctx):
    db, dev = ctx.database(), ctx.database()
    ctx.sql(db, PETS_SQL)
    before = ctx.catalog(db)
    hcl = ok(ctx.run("schema", "inspect", "-u", ctx.url(db)))
    assert_hcl(hcl, expected("pets.inspect.hcl"))
    out = ok(ctx.run("schema", "inspect", "-u", ctx.url(db), "--format", "{{ sql . }}"))
    assert_plan(out, PETS_STATEMENTS, [(0, 2), (2, 4), (3, 4), (4, 5), (4, 6), (4, 7)])
    out = ok(ctx.run("schema", "inspect", "-u", ctx.url(db), "--format", "{{ json . }}"))
    assert json_document(out) == json_document(expected("pets.inspect.json"))
    # The inspected HCL describes the database exactly.
    ctx.write("pets.hcl", hcl)
    assert_synced(ok(ctx.run("schema", "apply", "-u", ctx.url(db), "--to", "file://pets.hcl", "--dev-url", ctx.url(dev),
                             "--dry-run")))
    assert ctx.catalog(db) == before


BILLING_STATEMENTS = [
    'CREATE SCHEMA "billing"',
    """COMMENT ON SCHEMA "billing" IS 'money'""",
    *PUBLIC_SCHEMA,
    """CREATE TYPE "billing"."currency" AS ENUM ('usd', 'eur')""",
    """CREATE TABLE "public"."customers" ("id" integer NOT NULL, "name" text NOT NULL, PRIMARY KEY ("id"))""",
    """CREATE TABLE "billing"."invoices" ("id" bigint NOT NULL, "customer_id" integer NOT NULL,
      "cur" "billing"."currency" NOT NULL DEFAULT 'usd', "amount" numeric(9,3) NOT NULL DEFAULT 0.5,
      PRIMARY KEY ("id", "customer_id"), CONSTRAINT "inv_customer" FOREIGN KEY ("customer_id")
      REFERENCES "public"."customers" ("id") ON UPDATE CASCADE ON DELETE SET DEFAULT)""",
    """CREATE INDEX "inv_amount_brin" ON "billing"."invoices" USING brin ("amount")""",
]
BILLING_ORDER = [(0, 1), (0, 4), (0, 6), (2, 3), (2, 5), (4, 6), (5, 6), (6, 7)]


def test_inspect_multiple_schemas_and_filters(ctx):
    target, _ = apply(ctx, "billing.hcl")
    url = ctx.url(target)
    assert_hcl(ok(ctx.run("schema", "inspect", "-u", url)), expected("billing.inspect.hcl"))
    assert json_document(ok(ctx.run("schema", "inspect", "-u", url, "--format", "{{ json . }}"))) == json_document(
        expected("billing.inspect.json"))
    out = ok(ctx.run("schema", "inspect", "-u", url, "--schema", "billing", "--schema", "public", "--format", "{{ sql . }}"))
    assert_plan(out, BILLING_STATEMENTS, BILLING_ORDER)
    # A schema glob excludes the schema and everything in it.
    assert_hcl(ok(ctx.run("schema", "inspect", "-u", url, "--exclude", "billing")),
               expected("billing.exclude.inspect.hcl"))
    # A column glob removes just that column.
    out = ok(ctx.run("schema", "inspect", "-u", url, "--exclude", "*.invoices.amount", "--format", "{{ sql . }}"))
    without_amount = BILLING_STATEMENTS[:6] + [BILLING_STATEMENTS[6].replace(
        ', "amount" numeric(9,3) NOT NULL DEFAULT 0.5', "")]
    assert_plan(out, without_amount, BILLING_ORDER[:-1])


def test_inspect_does_not_modify_the_database(ctx):
    target, _ = apply(ctx, "billing.hcl")
    before = ctx.catalog(target)
    for fmt in ([], ["--format", "{{ sql . }}"], ["--format", "{{ json . }}"]):
        ok(ctx.run("schema", "inspect", "-u", ctx.url(target), *fmt))
    assert ctx.catalog(target) == before
    assert_catalog(ctx, ctx.database(), EMPTY_DATABASE)


def test_inspect_restricted_to_one_schema(ctx):
    target, _ = apply(ctx, "billing.hcl")
    public_only = expected("billing.exclude.inspect.hcl")
    assert_hcl(ok(ctx.run("schema", "inspect", "-u", ctx.url(target), "--schema", "public")), public_only)
    assert_hcl(ok(ctx.run("schema", "inspect", "-u", ctx.url(target, "public"))), public_only)
    # A schema-scoped URL describes the schema's contents only, with unqualified names.
    out = ok(ctx.run("schema", "inspect", "-u", ctx.url(target, "public"), "--format", "{{ sql . }}"))
    assert_plan(out, ['CREATE TABLE "customers" ("id" integer NOT NULL, "name" text NOT NULL, PRIMARY KEY ("id"))'])
