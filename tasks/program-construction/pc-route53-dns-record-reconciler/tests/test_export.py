def nameservers(zone):
    return zone.initial[("@", "NS")][2]


def tsv_lines(zone):
    z, i = zone.name, zone.id
    lines = [
        f"{z}\t@\t300\tIN\tA\t192.0.2.1",
        f"{z}\t@\t300\tIN\tMX\t10 mx.example.net.",
        f"{z}\t@\t300\tIN\tMX\t20 mx2.example.net.",
        f'{z}\t@\t600\tIN\tCAA\t0 issue "ca.example"',
        f"www.{z}\twww\t600\tIN\tA\t192.0.2.2",
        f"www.{z}\twww\t600\tIN\tA\t192.0.2.3",
        f"txt.{z}\ttxt\t600\tIN\tTXT\thello world",
        f"long.{z}\tlong\t600\tIN\tTXT\t" + "a" * 255 + "bbb",
        f"cn.{z}\tcn\t3600\tIN\tCNAME\ttarget.example.net.",
        f"_sip._tcp.{z}\t_sip._tcp\t600\tIN\tSRV\t10 20 5060 sip.example.net.",
        f"v6.{z}\tv6\t600\tIN\tAAAA\t2001:db8::1",
        f"al.{z}\tal\t300\tIN\tR53_ALIAS\tA www.{z}. false {i}",
        f"al2.{z}\tal2\t300\tIN\tR53_ALIAS\tA www.{z}. true {i}",
    ]
    return lines + [f"{z}\t@\t300\tIN\tNS\t{ns}" for ns in nameservers(zone)]


def without_soa_tsv(text):
    return Counter(line for line in text.splitlines() if line.strip() and line.split("\t")[4:5] != ["SOA"])


def test_tsv_export_and_legacy_form(project, exported):
    result = ok(project.run("get-zones", "--format=tsv", "r53", exported.name))
    assert without_soa_tsv(result.stdout) == Counter(tsv_lines(exported))
    legacy = ok(project.run("get-zones", "--format=tsv", "r53", "ROUTE53", exported.name))
    assert without_soa_tsv(legacy.stdout) == without_soa_tsv(result.stdout)
    assert legacy.stderr.strip()


def js_record_lines(zone):
    z, i = zone.name, zone.id
    return [
        "DnsProvider(DSP_R53)",
        "DefaultTTL(600)",
        'A("@", "192.0.2.1", TTL(300))',
        'MX("@", 10, "mx.example.net.", TTL(300))',
        'MX("@", 20, "mx2.example.net.", TTL(300))',
        'CAA("@", "issue", "ca.example")',
        'A("www", "192.0.2.2")',
        'A("www", "192.0.2.3")',
        'TXT("txt", "hello world")',
        'TXT("long", "' + "a" * 255 + 'bbb")',
        'CNAME("cn", "target.example.net.", TTL(3600))',
        'SRV("_sip._tcp", 10, 20, 5060, "sip.example.net.")',
        'AAAA("v6", "2001:db8::1")',
        f'R53_ALIAS("al", "A", "www.{z}.", R53_ZONE("{i}"), TTL(300))',
        f'R53_ALIAS("al2", "A", "www.{z}.", R53_ZONE("{i}"), R53_EVALUATE_TARGET_HEALTH(true), TTL(300))',
    ] + [f'//NAMESERVER("{ns}")' for ns in nameservers(zone)]


def js_lines(text):
    """Non-empty lines without indentation, separator commas or ';'; the SOA comment is not compared."""
    lines = Counter()
    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith("//, "):
            line = "//" + line[4:]
        line = line.removeprefix(", ").rstrip(";").rstrip(",")
        if line and not line.startswith("//SOA("):
            lines[line] += 1
    return lines


def leading_comma_body(text):
    """In the djs style every line inside D(...) other than the closing parenthesis starts with a comma."""
    lines = [line.strip() for line in text.splitlines()]
    opening = next(n for n, line in enumerate(lines) if line.startswith("D("))
    closing = next(n for n in range(opening, len(lines)) if lines[n].startswith(")"))
    return all(line.startswith((", ", "//, ")) for line in lines[opening + 1 : closing])


def js_expected(zone):
    return Counter(
        [
            "// generated by get-zones. This is 'a decent first draft' and requires editing.",
            'var DSP_R53 = NewDnsProvider("r53", "")',
            'var REG_CHANGEME = NewRegistrar("none")',
            f'D("{zone.name}", REG_CHANGEME',
            ")",
            *js_record_lines(zone),
        ]
    )


@pytest.mark.parametrize("style", ["js", "djs"])
def test_dsl_export_round_trips(project, exported, style):
    result = ok(project.run("get-zones", f"--format={style}", "r53", exported.name))
    assert js_lines(result.stdout) == js_expected(exported)
    assert leading_comma_body(result.stdout) == (style == "djs")
    project.write("exported.js", result.stdout)
    before = exported.state()
    ok(project.run("preview", "--config", "exported.js"), 0)
    assert exported.state() == before


def zone_file_records(text):
    """Parse the BIND output into (owner, ttl, type, data) using $TTL and owner continuation."""
    records, owner, default_ttl = Counter(), None, None
    for raw in text.splitlines():
        if not raw.strip():
            continue
        tokens = raw.split()
        if tokens[0] == "$ORIGIN":
            continue
        if tokens[0] == "$TTL":
            default_ttl = int(tokens[1])
            continue
        if not raw[0].isspace():
            owner, tokens = tokens[0], tokens[1:]
        ttl = default_ttl
        if tokens[0].isdigit():
            ttl, tokens = int(tokens[0]), tokens[1:]
        assert tokens[0] == "IN", raw
        if tokens[1] != "SOA":
            records[(owner, ttl, tokens[1], " ".join(tokens[2:]))] += 1
    return records


def test_zone_file_export(project, exported):
    z, i = exported.name, exported.id
    result = ok(project.run("get-zones", "--format=zone", "r53", z))
    assert result.stdout.splitlines()[0] == f"$ORIGIN {z}."
    expected = Counter(
        [
            ("@", 300, "A", "192.0.2.1"),
            ("@", 300, "MX", "10 mx.example.net."),
            ("@", 300, "MX", "20 mx2.example.net."),
            ("@", 600, "CAA", '0 issue "ca.example"'),
            ("www", 600, "A", "192.0.2.2"),
            ("www", 600, "A", "192.0.2.3"),
            ("txt", 600, "TXT", '"hello world"'),
            ("long", 600, "TXT", '"' + "a" * 255 + '" "bbb"'),
            ("cn", 3600, "CNAME", "target.example.net."),
            ("_sip._tcp", 600, "SRV", "10 20 5060 sip.example.net."),
            ("v6", 600, "AAAA", "2001:db8::1"),
            ("al", 300, "R53_ALIAS", f"A www.{z}. false {i}"),
            ("al2", 300, "R53_ALIAS", f"A www.{z}. true {i}"),
        ]
        + [("@", 300, "NS", ns) for ns in nameservers(exported)]
    )
    assert zone_file_records(result.stdout) == expected


def test_nameonly_all_and_output_file(project, exported, zones):
    second = zones("exq")
    result = ok(project.run("get-zones", "--format=nameonly", "r53", exported.name, second.name))
    assert Counter(result.stdout.split()) == Counter([exported.name, second.name])
    listed = ok(project.run("get-zones", "--format=nameonly", "r53", "all")).stdout.split()
    assert {exported.name, second.name} <= set(listed)
    assert len(listed) == len(set(listed))

    ok(project.run("get-zones", "--format=js", "--out", "zone-export.js", "r53", exported.name))
    assert js_lines((project.root / "zone-export.js").read_text()) == js_expected(exported)


def test_export_errors(project, exported):
    failed(project.run("get-zones", "--format=tsv", "r53", "absent-" + exported.name))
    failed(project.run("get-zones", "--format=bogus", "r53", exported.name))
