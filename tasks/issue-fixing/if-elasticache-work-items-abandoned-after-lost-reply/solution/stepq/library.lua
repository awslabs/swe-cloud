#!lua name=stepq

--[[
stepq queue library. Loaded by every executor at start (FUNCTION LOAD REPLACE) and called by
the executor fleet, the batch fleet and the ops tooling. Names, KEYS, ARGV and return codes are
the shared contract: see README.md.

Item JSON (field of {q}:queue:item): {"id", "partition", "at", "leaseID", "scavengeCount"}, plus
"runID" once an executor has started the item's step: the lease_id it sent the step runner, which names
the run there. It outlives the lease (a scavenged item keeps it) until q_requeue puts the item back for a
new run.
A lease ID is a ULID generated by the caller; its timestamp is the lease expiry in ms.
]]

local CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"

local function decode_ulid_time(ulid)
  local ts = 0
  for i = 1, 10 do
    local idx = string.find(CROCKFORD, string.sub(ulid, i, i), 1, true)
    ts = ts * 32 + (idx - 1)
  end
  return ts
end

local function get_item(keyItems, itemID)
  local raw = redis.call("HGET", keyItems, itemID)
  if raw == false or raw == nil then
    return nil
  end
  return cjson.decode(raw)
end

local function has_lease(item)
  return item.leaseID ~= nil and item.leaseID ~= cjson.null
end

local function server_now_ms()
  local t = redis.call("TIME")
  return tonumber(t[1]) * 1000 + math.floor(tonumber(t[2]) / 1000)
end

-- Point the partition's entry in {q}:concurrency at the earliest lease expiry in its
-- scavenger index, or drop it when nothing in the partition is leased.
local function update_pointer(keyConcurrency, keyScavenger, partition)
  local earliest = redis.call("ZRANGE", keyScavenger, 0, 0, "WITHSCORES")
  if earliest == false or earliest == nil or #earliest == 0 then
    redis.call("ZREM", keyConcurrency, partition)
  else
    redis.call("ZADD", keyConcurrency, tonumber(earliest[2]), partition)
  end
end

--[[
q_lease
  KEYS: {q}:queue:item, {q}:concurrency, {q}:queue:sorted:<p>, {q}:scavenger:<p>
  ARGV: itemID, partition, leaseID, nowMS
  0: leased (also when the stored lease is this same, unexpired leaseID: a retried call)
  -1: item not found   -2: item already leased   -3: leaseID already expired
]]
local function q_lease(keys, args)
  local keyItems, keyConcurrency, keyReady, keyScavenger = keys[1], keys[2], keys[3], keys[4]
  local itemID, partition, leaseID = args[1], args[2], args[3]
  local nowMS = tonumber(args[4])

  local item = get_item(keyItems, itemID)
  if item == nil then
    return -1
  end

  local expiry = decode_ulid_time(leaseID)
  if has_lease(item) and item.leaseID == leaseID then
    -- The caller's own lease, committed by an earlier attempt whose reply it never saw.
    if expiry > nowMS then
      return 0
    end
    return -3
  end
  if expiry <= nowMS then
    return -3
  end
  if has_lease(item) and decode_ulid_time(item.leaseID) > nowMS then
    -- Already leased: don't let this requester lease the item.
    return -2
  end

  item.leaseID = leaseID
  redis.call("HSET", keyItems, itemID, cjson.encode(item))
  -- In progress now: off the ready queue, onto the scavenger index scored by expiry.
  redis.call("ZREM", keyReady, itemID)
  redis.call("ZADD", keyScavenger, expiry, itemID)
  update_pointer(keyConcurrency, keyScavenger, partition)
  return 0
end

--[[
q_extend
  KEYS: {q}:queue:item, {q}:concurrency, {q}:scavenger:<p>
  ARGV: itemID, currentLeaseID, newLeaseID, partition
  0: extended   1: item not found   2: item has no lease   3: lease ID doesn't match
]]
local function q_extend(keys, args)
  local keyItems, keyConcurrency, keyScavenger = keys[1], keys[2], keys[3]
  local itemID, currentLeaseID, newLeaseID, partition = args[1], args[2], args[3], args[4]

  local item = get_item(keyItems, itemID)
  if item == nil then
    return 1
  end
  if not has_lease(item) then
    return 2
  end
  if item.leaseID == newLeaseID then
    -- A retried extension that already landed.
    return 0
  end
  if item.leaseID ~= currentLeaseID then
    return 3
  end

  item.leaseID = newLeaseID
  redis.call("HSET", keyItems, itemID, cjson.encode(item))
  redis.call("ZADD", keyScavenger, decode_ulid_time(newLeaseID), itemID)
  update_pointer(keyConcurrency, keyScavenger, partition)
  return 0
end

--[[
q_requeue: put an item back on its ready queue at runAtMS, removing any lease.
  KEYS: {q}:queue:item, {q}:concurrency, {q}:queue:sorted:<p>, {q}:scavenger:<p>
  ARGV: itemID, partition, leaseID, runAtMS
  0: requeued   1: item not found   2: the caller's lease is not the stored lease
]]
local function q_requeue(keys, args)
  local keyItems, keyConcurrency, keyReady, keyScavenger = keys[1], keys[2], keys[3], keys[4]
  local itemID, partition, leaseID = args[1], args[2], args[3]
  local runAtMS = tonumber(args[4])

  local item = get_item(keyItems, itemID)
  if item == nil then
    return 1
  end
  if not has_lease(item) or item.leaseID ~= leaseID then
    return 2
  end

  item.leaseID = cjson.null
  item.runID = nil
  item.at = runAtMS
  redis.call("HSET", keyItems, itemID, cjson.encode(item))
  redis.call("ZREM", keyScavenger, itemID)
  redis.call("ZADD", keyReady, runAtMS, itemID)
  update_pointer(keyConcurrency, keyScavenger, partition)
  return 0
end

--[[
q_dequeue: remove a finished item from the queue.
  KEYS: {q}:queue:item, {q}:concurrency, {q}:scavenger:<p>
  ARGV: itemID, partition, leaseID
  0: removed   1: item not found   2: the caller's lease is not the stored lease
]]
local function q_dequeue(keys, args)
  local keyItems, keyConcurrency, keyScavenger = keys[1], keys[2], keys[3]
  local itemID, partition, leaseID = args[1], args[2], args[3]

  local item = get_item(keyItems, itemID)
  if item == nil then
    return 1
  end
  if not has_lease(item) or item.leaseID ~= leaseID then
    return 2
  end

  redis.call("HDEL", keyItems, itemID)
  redis.call("ZREM", keyScavenger, itemID)
  update_pointer(keyConcurrency, keyScavenger, partition)
  return 0
end

--[[
q_scavenge: return an item whose lease has expired to its ready queue, due now.
  KEYS: {q}:queue:item, {q}:concurrency, {q}:queue:sorted:<p>, {q}:scavenger:<p>
  ARGV: itemID, partition, nowMS
  0: requeued   1: item not found   2: not expired (or no longer leased)
]]
local function q_scavenge(keys, args)
  local keyItems, keyConcurrency, keyReady, keyScavenger = keys[1], keys[2], keys[3], keys[4]
  local itemID, partition = args[1], args[2]
  local nowMS = tonumber(args[3])

  local item = get_item(keyItems, itemID)
  if item == nil then
    -- Drop the dangling reference so the scavenger doesn't spin on it.
    redis.call("ZREM", keyScavenger, itemID)
    update_pointer(keyConcurrency, keyScavenger, partition)
    return 1
  end

  -- The caller's scan may be stale: decide from the lease stored now.
  local now = math.min(nowMS, server_now_ms())
  if not has_lease(item) then
    redis.call("ZREM", keyScavenger, itemID)
    update_pointer(keyConcurrency, keyScavenger, partition)
    return 2
  end
  local expiry = decode_ulid_time(item.leaseID)
  if expiry > now then
    redis.call("ZADD", keyScavenger, expiry, itemID)
    update_pointer(keyConcurrency, keyScavenger, partition)
    return 2
  end

  item.scavengeCount = (tonumber(item.scavengeCount) or 0) + 1
  item.leaseID = cjson.null
  item.at = nowMS
  redis.call("HSET", keyItems, itemID, cjson.encode(item))
  redis.call("ZREM", keyScavenger, itemID)
  redis.call("ZADD", keyReady, nowMS, itemID)
  update_pointer(keyConcurrency, keyScavenger, partition)
  return 0
end

--[[
q_start: the run an executor holding the item's lease is to send the step runner. The first caller
records its lease as the run; later callers (a retry, or the next holder after the first one died) get
that recorded run back, so the runner attaches them to it instead of running the step again.
  KEYS: {q}:queue:item
  ARGV: itemID, leaseID
  the run's lease ID (string)   1: item not found   3: the caller's lease is not the stored lease
]]
local function q_start(keys, args)
  local keyItems = keys[1]
  local itemID, leaseID = args[1], args[2]

  local item = get_item(keyItems, itemID)
  if item == nil then
    return 1
  end
  if not has_lease(item) or item.leaseID ~= leaseID then
    return 3
  end
  if item.runID == nil or item.runID == cjson.null then
    item.runID = leaseID
    redis.call("HSET", keyItems, itemID, cjson.encode(item))
  end
  return item.runID
end

redis.register_function("q_lease", q_lease)
redis.register_function("q_extend", q_extend)
redis.register_function("q_requeue", q_requeue)
redis.register_function("q_dequeue", q_dequeue)
redis.register_function("q_scavenge", q_scavenge)
redis.register_function("q_start", q_start)
